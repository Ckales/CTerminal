/// 界面语言。源码里直接写中文，英文时查表；表里没有的原样显示（方便发现漏翻）。
/// 带参数的文本用 {name} 占位：tr('还有 {count} 个会话', {'count': 3})
String _language = 'zh';

String get currentLanguage => _language;

/// setting: system / zh-CN / en
String resolveLanguage(String setting) {
  if (setting == 'en') return 'en';
  if (setting == 'zh-CN') return 'zh';
  return PlatformDispatcher.instance.locale.languageCode == 'zh' ? 'zh' : 'en';
}

void setLanguage(String code) => _language = code;

String tr(String source, [Map<String, Object?> args = const {}]) {
  var text = _language == 'en' ? (_english[source] ?? source) : source;
  args.forEach((key, value) => text = text.replaceAll('{$key}', '$value'));
  return text;
}

